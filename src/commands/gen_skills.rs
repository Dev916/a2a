//! `a2a __gen-skills --out <dir> [--check]` — render the generated skill
//! artifacts from their in-repo sources (spec §4.7, §8.9).
//!
//! **Why one source.** The worker protocol has to be in two places at once. The
//! load-bearing copy lives in `~/.codex/AGENTS.md`, because a Codex skill is
//! model-invoked (description-triggered) and therefore discretionary — a
//! protocol that must *always* govern cannot ride on one. The `a2a-worker`
//! skill is the supplementary elaboration a worker reaches for when it notices
//! it is a worker. Two hand-maintained copies of a security protocol diverge:
//! silently, and in the direction of whichever copy somebody last remembered.
//! So there is exactly one source — `skills/worker-protocol.md` — every copy is
//! rendered from it, and `tests/skills_gen.rs` fails the build when the
//! checked-in renderings and the source disagree.
//!
//! **Why HTML section markers.** The source is a normal, readable Markdown file
//! (it is the thing a human edits when the protocol changes), so the renderer
//! needs a slicing seam that survives ordinary Markdown editing and never
//! collides with the prose. `<!-- a2a:section <id> -->` … `<!-- a2a:end <id> -->`
//! is invisible in every renderer, greppable, and — unlike "slice on `## `" —
//! cannot be broken by a heading appearing inside a fenced code block.
//!
//! **What this command is NOT.** It never installs. It writes under `--out` and
//! nowhere else: no symlink into `~/.claude/skills`, no copy into
//! `~/.codex/skills`, no edit to `~/.codex/AGENTS.md`. Installation is a
//! separate, consent-bearing step; a renderer that quietly edited a developer's
//! global agent instructions would be the most surprising thing in this
//! binary. `tests/skills_gen.rs` pins that by running the command with `HOME`
//! and `CODEX_HOME` pointed at an empty tempdir and asserting it stays empty.
//!
//! **Why it is hidden.** `__gen-skills` is a maintenance command for this
//! repository's own build, not an operator-facing verb: `--check` is a CI gate
//! and `--out` only makes sense against a checkout. Hidden keeps `a2a --help`
//! about dispatching workers.

use crate::output::{AppError, ExitCode, Outcome};
use serde_json::json;
use std::path::Path;

/// THE source of the worker protocol. Everything a Codex worker is told about
/// data-vs-instructions, cwd discipline, blocking, progress and evidence is a
/// rendering of this file.
pub const WORKER_PROTOCOL_SRC: &str = include_str!("../../skills/worker-protocol.md");

/// THE source of the orchestrator protocol (spec §4.8) — the Claude side's
/// half of the same contract: when to dispatch a Codex worker at all, how to
/// write a brief a memoryless worker can finish, how to watch one without
/// spending the context window the dispatch was meant to save, and how the
/// acceptance gate stays mechanical.
///
/// It is a *separate* source from [`WORKER_PROTOCOL_SRC`] because the two
/// audiences are different — the worker is told what it may do, the
/// orchestrator is told what to ask for — but it goes through the same renderer
/// and the same drift gate, so neither copy can quietly rot.
pub const ORCHESTRATE_SRC: &str = include_str!("../../skills/orchestrate-protocol.md");

/// The one line that tells a reader of a generated file where to send an edit.
/// Identical in all three artifacts on purpose: the question it answers is
/// "is this file hand-editable?", and the answer is the same everywhere.
pub const PROVENANCE: &str = "<!-- generated from skills/worker-protocol.md by `a2a __gen-skills`; edit the source, not this file -->";

/// The fences that delimit a2a's region of `~/.codex/AGENTS.md`. They are how a
/// future installer finds the block it may replace — everything outside them is
/// the user's, and is never touched.
pub const AGENTS_BEGIN: &str =
    "<!-- BEGIN a2a worker protocol (generated by `a2a __gen-skills`; do not edit) -->";
pub const AGENTS_END: &str = "<!-- END a2a worker protocol -->";

/// The worker protocol's sections, in the order they are rendered. Pinned: a
/// missing, renamed or reordered section is a source error, not a quiet
/// difference in the artifact.
pub const REQUIRED_SECTIONS: [&str; 6] = [
    "data-not-instructions",
    "cwd-discipline",
    "blocked-protocol",
    "progress-notices",
    "result-and-evidence",
    "worktree-notes",
];

/// The orchestrator protocol's sections, in render order — spec §4.8's bullets,
/// one id each. Pinned for the same reason [`REQUIRED_SECTIONS`] is: a dropped
/// section is a piece of guidance an orchestrator silently stops being given.
pub const ORCHESTRATE_SECTIONS: [&str; 8] = [
    "dispatch-choice",
    "brief-writing",
    "monitor-loop",
    "answering-blocked",
    "acceptance-gate",
    "worktree-hygiene",
    "ownership",
    "devloop-dispatch",
];

/// Relative paths under `--out`, in the order [`render`] returns them.
pub const ARTIFACTS: [&str; 3] = [
    "codex/a2a-worker/SKILL.md",
    "codex/AGENTS-section.md",
    "claude/a2a-orchestrate/SKILL.md",
];

/// One `<!-- a2a:section id -->` … `<!-- a2a:end id -->` block of a source.
#[derive(Debug, Clone, Copy)]
pub struct Section<'a> {
    pub id: &'a str,
    /// The block's Markdown, with the markers removed and the surrounding
    /// blank lines trimmed.
    pub body: &'a str,
}

fn source_error(msg: impl Into<String>) -> AppError {
    // A compiled-in source that does not parse is a bug in this repository, not
    // an operator mistake — hence Internal rather than Precondition.
    AppError::new("SKILLS_SOURCE_INVALID", ExitCode::Internal, msg.into()).remedy(
        "fix the source under `skills/`: YAML front matter, then `<!-- a2a:section <id> -->` … \
         `<!-- a2a:end <id> -->` blocks",
    )
}

/// Split `---`-fenced YAML front matter off the front of a source.
///
/// Returns `(front matter body, everything after the closing fence)`, both with
/// their outer blank lines trimmed.
pub fn front_matter(src: &str) -> Result<(&str, &str), AppError> {
    let rest = src
        .strip_prefix("---\n")
        .ok_or_else(|| source_error("source does not open with `---` front matter"))?;
    // The closing fence is a line that is exactly `---`.
    let mut offset = 0usize;
    for line in rest.split_inclusive('\n') {
        if line.trim_end_matches('\n') == "---" {
            let front = &rest[..offset];
            let body = &rest[offset + line.len()..];
            return Ok((front.trim(), body.trim_start_matches('\n')));
        }
        offset += line.len();
    }
    Err(source_error("front matter is never closed by a `---` line"))
}

/// Slice a source into its `a2a:section` blocks, in source order.
///
/// Deliberately *not* id-validating: the worker protocol and the orchestrator
/// protocol have different section sets, and the id list each one must carry is
/// checked by its own renderer.
pub fn parse_sections(src: &str) -> Result<Vec<Section<'_>>, AppError> {
    const OPEN: &str = "<!-- a2a:section ";
    const CLOSE: &str = "<!-- a2a:end ";
    const TAIL: &str = " -->";

    let mut out: Vec<Section<'_>> = Vec::new();
    let mut open: Option<(&str, usize)> = None; // (id, body start offset)
    let mut offset = 0usize;
    for line in src.split_inclusive('\n') {
        let trimmed = line.trim();
        let next = offset + line.len();
        if let Some(rest) = trimmed.strip_prefix(OPEN) {
            let id = rest
                .strip_suffix(TAIL)
                .ok_or_else(|| source_error(format!("malformed section marker: {trimmed}")))?
                .trim();
            if let Some((prev, _)) = open {
                return Err(source_error(format!(
                    "section `{prev}` is still open at section `{id}`"
                )));
            }
            if out.iter().any(|s| s.id == id) {
                return Err(source_error(format!("duplicate section `{id}`")));
            }
            open = Some((id, next));
        } else if let Some(rest) = trimmed.strip_prefix(CLOSE) {
            let id = rest
                .strip_suffix(TAIL)
                .ok_or_else(|| source_error(format!("malformed end marker: {trimmed}")))?
                .trim();
            let (open_id, start) = open
                .take()
                .ok_or_else(|| source_error(format!("`{id}` ends without opening")))?;
            if open_id != id {
                return Err(source_error(format!(
                    "section `{open_id}` is closed by `{id}`"
                )));
            }
            out.push(Section {
                id: open_id,
                body: src[start..offset].trim(),
            });
        }
        offset = next;
    }
    if let Some((id, _)) = open {
        return Err(source_error(format!("section `{id}` is never closed")));
    }
    if out.is_empty() {
        return Err(source_error("source carries no `a2a:section` blocks"));
    }
    Ok(out)
}

fn require_ids(got: &[Section<'_>], want: &[&str], what: &str) -> Result<(), AppError> {
    let ids: Vec<&str> = got.iter().map(|s| s.id).collect();
    if ids != want {
        return Err(source_error(format!(
            "{what} sections are {ids:?}, expected {want:?} in that order"
        )));
    }
    Ok(())
}

/// The sections, joined the way both artifacts join them: one blank line
/// between blocks, no trailing newline (the caller owns the file's ending).
fn body_of(sections: &[Section<'_>]) -> String {
    sections
        .iter()
        .map(|s| s.body)
        .collect::<Vec<_>>()
        .join("\n\n")
}

/// A Codex/Claude skill file: the source's own front matter, the provenance
/// comment on the first line after it, then every section in order.
fn render_skill(src: &str) -> Result<String, AppError> {
    let (front, body) = front_matter(src)?;
    let sections = parse_sections(body)?;
    Ok(format!(
        "---\n{front}\n---\n{PROVENANCE}\n\n{}\n",
        body_of(&sections)
    ))
}

/// The load-bearing copy: no front matter (it is spliced into a file that has
/// none), fenced so an installer can find and replace exactly a2a's region.
fn render_agents_section(src: &str) -> Result<String, AppError> {
    let (_front, body) = front_matter(src)?;
    let sections = parse_sections(body)?;
    require_ids(&sections, &REQUIRED_SECTIONS, "worker protocol")?;
    Ok(format!(
        "{AGENTS_BEGIN}\n{PROVENANCE}\n\n{}\n\n{AGENTS_END}\n",
        body_of(&sections)
    ))
}

/// A source's sections, past its front matter — the pair every id check starts
/// from.
fn sections_of(src: &str) -> Result<Vec<Section<'_>>, AppError> {
    let (_front, body) = front_matter(src)?;
    parse_sections(body)
}

/// `(relative path under --out, rendered bytes)` for all three artifacts.
///
/// Both sources are id-checked BEFORE anything is rendered: a source missing a
/// section still renders a plausible-looking artifact, and the drift gate would
/// happily bless it. The two lists are separate because the two protocols are
/// (spec §4.7 for the worker, §4.8 for the orchestrator).
pub fn render() -> Result<Vec<(&'static str, String)>, AppError> {
    require_ids(
        &sections_of(WORKER_PROTOCOL_SRC)?,
        &REQUIRED_SECTIONS,
        "worker protocol",
    )?;
    require_ids(
        &sections_of(ORCHESTRATE_SRC)?,
        &ORCHESTRATE_SECTIONS,
        "orchestrator protocol",
    )?;
    Ok(vec![
        (ARTIFACTS[0], render_skill(WORKER_PROTOCOL_SRC)?),
        (ARTIFACTS[1], render_agents_section(WORKER_PROTOCOL_SRC)?),
        (ARTIFACTS[2], render_skill(ORCHESTRATE_SRC)?),
    ])
}

pub fn run(out: &Path, check: bool, json_mode: bool, quiet: bool) -> Result<Outcome, AppError> {
    let artifacts = render()?;

    if check {
        // Byte comparison, and a missing file counts as drift: "the artifact is
        // not there" and "the artifact is stale" are the same failure for a
        // gate whose job is to guarantee the checked-in copies are current.
        let drifted: Vec<&str> = artifacts
            .iter()
            .filter(|(rel, want)| match std::fs::read(out.join(rel)) {
                Ok(got) => got != want.as_bytes(),
                Err(_) => true,
            })
            .map(|(rel, _)| *rel)
            .collect();
        if !drifted.is_empty() {
            return Err(AppError::new(
                "SKILLS_DRIFT",
                ExitCode::Precondition,
                format!(
                    "generated skill artifacts differ from their source: {}",
                    drifted.join(", ")
                ),
            )
            .remedy(format!(
                "re-render them: `a2a __gen-skills --out {}`",
                out.display()
            ))
            .data(json!({"drifted": drifted})));
        }
        return Ok(Outcome::from(json!({
            "out": out.display().to_string(),
            "checked": artifacts.iter().map(|(rel, _)| *rel).collect::<Vec<_>>(),
            "drifted": [],
        })));
    }

    for (rel, body) in &artifacts {
        let path = out.join(rel);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(|e| write_failed(parent, &e))?;
        }
        std::fs::write(&path, body).map_err(|e| write_failed(&path, &e))?;
        if !quiet && !json_mode {
            eprintln!("a2a: wrote {}", path.display());
        }
    }
    Ok(Outcome::from(json!({
        "out": out.display().to_string(),
        "written": artifacts.iter().map(|(rel, _)| *rel).collect::<Vec<_>>(),
    })))
}

fn write_failed(path: &Path, e: &std::io::Error) -> AppError {
    AppError::new(
        "SKILLS_WRITE_FAILED",
        ExitCode::Precondition,
        format!("cannot write {}: {e}", path.display()),
    )
    .remedy("point `--out` at a writable directory")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_worker_protocol_source_carries_exactly_the_pinned_sections_in_order() {
        let (front, body) = front_matter(WORKER_PROTOCOL_SRC).expect("front matter parses");
        assert!(front.contains("name: a2a-worker"), "{front}");
        let sections = parse_sections(body).expect("sections parse");
        let ids: Vec<&str> = sections.iter().map(|s| s.id).collect();
        assert_eq!(ids, REQUIRED_SECTIONS.to_vec());
        // Every section has prose; an empty block would render an artifact that
        // passes the drift gate and teaches a worker nothing.
        for s in &sections {
            assert!(s.body.len() > 80, "section `{}` is a stub", s.id);
        }
    }

    #[test]
    fn the_orchestrate_source_carries_exactly_the_pinned_sections_in_order() {
        let (front, body) = front_matter(ORCHESTRATE_SRC).expect("front matter parses");
        assert!(front.contains("name: a2a-orchestrate"), "{front}");
        let sections = parse_sections(body).expect("sections parse");
        let ids: Vec<&str> = sections.iter().map(|s| s.id).collect();
        assert_eq!(ids, ORCHESTRATE_SECTIONS.to_vec());
        for s in &sections {
            assert!(s.body.len() > 80, "section `{}` is a stub", s.id);
        }
    }

    #[test]
    fn a_source_that_does_not_parse_is_an_error_rather_than_a_silent_artifact() {
        assert!(front_matter("## no front matter\n").is_err());
        assert!(front_matter("---\nname: x\nnever closed\n").is_err());
        let unclosed = "<!-- a2a:section a -->\nbody\n";
        assert!(parse_sections(unclosed).is_err());
        let mismatched = "<!-- a2a:section a -->\nbody\n<!-- a2a:end b -->\n";
        assert!(parse_sections(mismatched).is_err());
        let nested = "<!-- a2a:section a -->\n<!-- a2a:section b -->\n";
        assert!(parse_sections(nested).is_err());
        let dangling = "<!-- a2a:end a -->\n";
        assert!(parse_sections(dangling).is_err());
        assert!(parse_sections("just prose\n").is_err());
    }

    #[test]
    fn every_artifact_ends_with_one_newline_and_names_its_source() {
        for (rel, body) in render().expect("render") {
            assert!(body.ends_with('\n'), "{rel} has no trailing newline");
            assert!(!body.ends_with("\n\n"), "{rel} has more than one");
            assert!(body.contains(PROVENANCE), "{rel} lost its provenance");
            assert!(
                !body.contains("<!-- a2a:section "),
                "{rel} leaked a slicing marker"
            );
        }
    }

    #[test]
    fn the_agents_copy_is_fenced_and_the_skill_copy_is_front_mattered() {
        let rendered = render().expect("render");
        let skill = &rendered[0].1;
        let agents = &rendered[1].1;
        assert!(skill.starts_with("---\n"));
        // The line after the *closing* fence is the provenance comment.
        let close = skill
            .lines()
            .skip(1)
            .position(|l| l == "---")
            .expect("front matter closes");
        assert_eq!(
            skill.lines().nth(close + 2),
            Some(PROVENANCE),
            "provenance is the first line after the front matter"
        );
        assert!(agents.starts_with(AGENTS_BEGIN));
        assert!(agents.trim_end().ends_with(AGENTS_END));
        assert!(!agents.starts_with("---"));
    }
}
