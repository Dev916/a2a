//! `a2a __gen-skills` — the drift gate for the generated skill artifacts.
//!
//! The worker protocol has to exist in two places at once (`~/.codex/AGENTS.md`,
//! which always governs, and the discretionary `a2a-worker` skill), and two
//! hand-maintained copies of a security protocol diverge — silently, and in the
//! direction of whichever copy somebody last remembered. So there is exactly one
//! source, `skills/worker-protocol.md`, and this file is the mechanism that
//! keeps the checked-in renderings honest:
//!
//! * one test runs `--check` against the checked-in `skills/generated`, which is
//!   what fails CI the moment somebody edits an artifact or the source alone;
//! * a second renders into a tempdir and byte-diffs, so a `--check` that
//!   accidentally compared nothing could not satisfy the first.
//!
//! Nothing here reads or writes anything under the developer's real `$HOME`,
//! `~/.codex` or `~/.claude` — the no-live-install test proves that by pointing
//! `HOME`/`CODEX_HOME` at an empty tempdir and asserting it stays empty.

use assert_cmd::Command;
use serde_json::Value;
use std::path::{Path, PathBuf};

/// The three artifacts, in the order `render()` returns them.
const ARTIFACTS: [&str; 3] = [
    "codex/a2a-worker/SKILL.md",
    "codex/AGENTS-section.md",
    "claude/a2a-orchestrate/SKILL.md",
];
const PROVENANCE: &str =
    "<!-- generated from skills/worker-protocol.md by `a2a __gen-skills`; edit the source, not this file -->";
const AGENTS_BEGIN: &str =
    "<!-- BEGIN a2a worker protocol (generated by `a2a __gen-skills`; do not edit) -->";
const AGENTS_END: &str = "<!-- END a2a worker protocol -->";

fn checked_in_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("skills/generated")
}

fn a2a() -> Command {
    Command::cargo_bin("a2a").unwrap()
}

/// Every entry (files AND directories) under `root`, as `/`-joined relative
/// paths. Used both to enumerate a render and to assert a tempdir is untouched.
fn walk(root: &Path) -> Vec<String> {
    fn rec(dir: &Path, prefix: &str, out: &mut Vec<String>) {
        let Ok(rd) = std::fs::read_dir(dir) else {
            return;
        };
        for entry in rd.flatten() {
            let name = entry.file_name().to_string_lossy().into_owned();
            let rel = if prefix.is_empty() {
                name
            } else {
                format!("{prefix}/{name}")
            };
            let is_dir = entry.metadata().map(|m| m.is_dir()).unwrap_or(false);
            out.push(rel.clone());
            if is_dir {
                rec(&entry.path(), &rel, out);
            }
        }
    }
    let mut out = Vec::new();
    rec(root, "", &mut out);
    out.sort();
    out
}

fn files_under(root: &Path) -> Vec<String> {
    walk(root)
        .into_iter()
        .filter(|rel| root.join(rel).is_file())
        .collect()
}

/// A fresh render of all three artifacts into a tempdir.
fn render_into_tempdir() -> tempfile::TempDir {
    let out = tempfile::tempdir().unwrap();
    a2a()
        .arg("__gen-skills")
        .arg("--out")
        .arg(out.path())
        .assert()
        .success();
    out
}

fn read(dir: &Path, rel: &str) -> String {
    std::fs::read_to_string(dir.join(rel)).unwrap_or_else(|e| panic!("read {rel}: {e}"))
}

/// Collapse every run of whitespace to one space.
///
/// The prompt-contract pins below are about *sentences*, and the source is a
/// hard-wrapped Markdown file — a rule that a re-flow of a paragraph could turn
/// red would be a rule people delete rather than fix. Flattening first keeps
/// the assertion on what the worker is told, not on where the source wraps.
fn flat(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

