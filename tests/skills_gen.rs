#[test]
fn every_artifact_ends_with_exactly_one_trailing_newline() {
    let out = render_into_tempdir();
    for rel in ARTIFACTS {
        let body = read(out.path(), rel);
        assert!(body.ends_with('\n'), "{rel} has no trailing newline");
        assert!(!body.ends_with("\n\n"), "{rel} has more than one");
    }
}

#[test]
fn the_codex_skill_carries_front_matter_then_provenance() {
    let out = render_into_tempdir();
    let body = read(out.path(), ARTIFACTS[0]);
    let mut lines = body.lines();
    assert_eq!(lines.next(), Some("---"), "front matter opens the skill");
    let mut front = Vec::new();
    for line in lines.by_ref() {
        if line == "---" {
            break;
        }
        front.push(line);
    }
    let front = front.join("\n");
    assert!(front.contains("name: a2a-worker"), "front matter: {front}");
    assert!(
        front.contains("description:"),
        "the skill is model-invoked, so the description is the trigger: {front}"
    );
    assert!(front.contains("version:"), "front matter: {front}");
    // The provenance comment is the first line after the front matter.
    assert_eq!(lines.next(), Some(PROVENANCE));
}

#[test]
fn the_agents_section_is_fenced_and_carries_no_front_matter() {
    let out = render_into_tempdir();
    let body = read(out.path(), ARTIFACTS[1]);
    let lines: Vec<&str> = body.lines().collect();
    assert_eq!(lines[0], AGENTS_BEGIN, "the fence opens the file");
    assert_eq!(lines[1], PROVENANCE, "provenance follows the fence");
    assert_eq!(
        lines.last().copied(),
        Some(AGENTS_END),
        "the fence closes the file"
    );
    assert!(
        !body.starts_with("---"),
        "the AGENTS.md section must not carry YAML front matter"
    );
}

#[test]
fn the_orchestrate_skill_is_rendered_with_its_own_front_matter() {
    let out = render_into_tempdir();
    let body = read(out.path(), ARTIFACTS[2]);
    assert!(body.starts_with("---\n"), "front matter opens the skill");
    assert!(body.contains("name: a2a-orchestrate"), "{body}");
    assert!(body.contains(PROVENANCE), "{body}");
    // The skill is model-invoked, so the description IS the trigger — an
    // orchestrator that never loads it is an orchestrator that guesses.
    let front = flat(body.split("---").nth(1).expect("front matter"));
    for trigger in ["dispatch a codex worker", "/a2a", "spawn a worker"] {
        assert!(
            front.contains(trigger),
            "the description does not name the trigger `{trigger}`: {front}"
        );
    }
}

