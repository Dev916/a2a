/// The renderer writes under `--out` and nowhere else. Proven by pointing
/// `HOME` and `CODEX_HOME` at an empty tempdir and asserting it is still empty
/// — never by stat-ing the developer's real `~/.codex` or `~/.claude`.
#[test]
fn gen_skills_writes_only_under_out_and_never_installs() {
    let out = tempfile::tempdir().unwrap();
    let sandbox_home = tempfile::tempdir().unwrap();
    a2a()
        .env("HOME", sandbox_home.path())
        .env("CODEX_HOME", sandbox_home.path())
        .arg("__gen-skills")
        .arg("--out")
        .arg(out.path())
        .assert()
        .success();

    let touched = walk(sandbox_home.path());
    assert!(
        touched.is_empty(),
        "the command wrote into $HOME/$CODEX_HOME: {touched:?}"
    );

    let mut rendered = files_under(out.path());
    rendered.sort();
    let mut expected: Vec<String> = ARTIFACTS.iter().map(|s| s.to_string()).collect();
    expected.sort();
    assert_eq!(
        rendered, expected,
        "--out holds exactly the three artifacts"
    );
}
