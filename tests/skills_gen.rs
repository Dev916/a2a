/// `--check` against the checked-in artifacts. This is the test that turns red
/// when the source and its renderings disagree.
#[test]
fn the_checked_in_artifacts_agree_with_the_source() {
    a2a()
        .arg("__gen-skills")
        .arg("--out")
        .arg(checked_in_dir())
        .arg("--check")
        .assert()
        .success();
}

/// The other half of the gate: a real render, byte-compared against the
/// checked-in copies. A `--check` that compared nothing would pass the test
/// above and fail this one.
#[test]
fn a_fresh_render_byte_matches_every_checked_in_artifact() {
    let out = render_into_tempdir();
    for rel in ARTIFACTS {
        let fresh = std::fs::read(out.path().join(rel)).unwrap();
        let stored = std::fs::read(checked_in_dir().join(rel))
            .unwrap_or_else(|e| panic!("checked-in {rel} is missing: {e}"));
        assert_eq!(
            String::from_utf8_lossy(&stored),
            String::from_utf8_lossy(&fresh),
            "{rel} drifted from the source; re-run `a2a __gen-skills --out skills/generated`"
        );
    }
}

/// A rendered artifact that drifted is named — in the message and in `data` —
/// so a CI failure says which file to regenerate.
#[test]
fn check_exits_nine_and_names_each_drifted_artifact() {
    let out = render_into_tempdir();
    // Two drifted artifacts: one edited, one deleted. Both must be named.
    let edited = out.path().join(ARTIFACTS[1]);
    let mut body = std::fs::read_to_string(&edited).unwrap();
    body.push_str("\nhand-edited\n");
    std::fs::write(&edited, body).unwrap();
    std::fs::remove_file(out.path().join(ARTIFACTS[0])).unwrap();

    let assert = a2a()
        .arg("--json")
        .arg("__gen-skills")
        .arg("--out")
        .arg(out.path())
        .arg("--check")
        .assert()
        .code(9);
    let stdout = String::from_utf8_lossy(&assert.get_output().stdout).into_owned();
    let env: Value = serde_json::from_str(stdout.trim()).expect("one JSON envelope on stdout");
    assert_eq!(env["ok"], false);
    assert_eq!(env["error"]["code"], "SKILLS_DRIFT");
    let msg = env["error"]["message"].as_str().unwrap();
    let drifted: Vec<String> = env["error"]["data"]["drifted"]
        .as_array()
        .expect("data.drifted is an array")
        .iter()
        .map(|v| v.as_str().unwrap().to_string())
        .collect();
    for rel in [ARTIFACTS[0], ARTIFACTS[1]] {
        assert!(
            drifted.contains(&rel.to_string()),
            "{rel} missing from {drifted:?}"
        );
        assert!(msg.contains(rel), "message does not name {rel}: {msg}");
    }
    assert!(
        !drifted.contains(&ARTIFACTS[2].to_string()),
        "the untouched artifact was reported as drifted: {drifted:?}"
    );
}

/// An untouched render is clean, and `--check` writes nothing.
#[test]
fn check_is_green_and_side_effect_free_on_a_fresh_render() {
    let out = render_into_tempdir();
    let before = walk(out.path());
    a2a()
        .arg("__gen-skills")
        .arg("--out")
        .arg(out.path())
        .arg("--check")
        .assert()
        .success();
    assert_eq!(before, walk(out.path()));
}

